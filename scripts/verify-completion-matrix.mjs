#!/usr/bin/env node
/**
 * verify-completion-matrix.mjs
 *
 * Master Plan completion-matrix validator + reporter.
 *
 * - Validates docs/master-plan/completion-matrix.json structure (schemaVersion,
 *   metadata, phases, status enum, percent ranges, unique phase ids).
 * - Validates that every evidence path listed in the matrix actually exists
 *   in the repository.
 * - Validates overall rollup consistency against the included phases.
 * - Regenerates docs/master-plan/completion-matrix.md from the JSON and, in
 *   `--check` mode (default), fails if the committed markdown is out of sync.
 *   Use `--write` to regenerate the markdown report.
 *
 * Usage:
 *   node scripts/verify-completion-matrix.mjs [--write] [path/to/matrix.json]
 *
 * Exit codes: 0 = valid, 1 = invalid / out of sync.
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs"
import { join, dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const DEFAULT_MATRIX = join(ROOT, "docs", "master-plan", "completion-matrix.json")
const DEFAULT_REPORT = join(ROOT, "docs", "master-plan", "completion-matrix.md")

const VALID_STATUSES = new Set(["completed", "partial", "not-started", "out-of-scope"])

function fail(message) {
  console.error(`\n✖ completion-matrix validation FAILED:\n   ${message}`)
  process.exitCode = 1
}

function formatPercent(value) {
  return `${Math.round(value)}%`
}

function renderMarkdown(matrix) {
  const { metadata, overall, phases } = matrix
  const byId = new Map(phases.map((p) => [p.id, p]))
  const included = overall.includedPhases.map((id) => byId.get(id)).filter(Boolean)
  const equalWeight = included.length
    ? included.reduce((sum, p) => sum + p.percent, 0) / included.length
    : 0

  const statusIcon = (status) =>
    status === "completed" ? "✅" : status === "partial" ? "🟡" : status === "not-started" ? "⬜" : "🚫"

  const lines = []
  lines.push("# FlowDeck Master Plan — Completion Matrix")
  lines.push("")
  lines.push("> **Generated report** — do not edit by hand. Edit `completion-matrix.json` and run")
  lines.push("> `npm run verify:completion-matrix -- --write` to regenerate.")
  lines.push("")
  lines.push(`- **Repository**: \`${metadata.repository}\``)
  lines.push(`- **Branch**: \`${metadata.branch}\``)
  lines.push(`- **Last measured**: \`${overall.lastMeasuredAt}\``)
  lines.push(`- **Overall completion (declared)**: **${formatPercent(overall.completionPercent)}**`)
  lines.push(`- **Overall completion (equal-weight rollup)**: ${formatPercent(equalWeight)}`)
  lines.push(`- **Included phases**: ${overall.includedPhases.map((id) => `\`${id}\``).join(", ")}`)
  lines.push(`- **Excluded phases**: ${overall.excludedPhases.map((id) => `\`${id}\``).join(", ") || "none"}`)
  lines.push("")
  lines.push(`> ${metadata.scopeNote}`)
  lines.push("")
  lines.push("## Phase Status")
  lines.push("")
  lines.push("| Phase | Name | Status | Completion | Key deliverables |")
  lines.push("| :--- | :--- | :--- | ---: | :--- |")
  for (const phase of phases) {
    const deliverables = phase.keyDeliverables.length ? phase.keyDeliverables[0] : "—"
    lines.push(
      `| ${phase.id} | ${phase.name} | ${statusIcon(phase.status)} ${phase.status} | ${formatPercent(phase.percent)} | ${deliverables} |`,
    )
  }
  lines.push("")
  lines.push("## Phase Details")
  lines.push("")
  for (const phase of phases) {
    lines.push(`### Phase ${phase.id} — ${phase.name} (${formatPercent(phase.percent)}, ${phase.status})`)
    lines.push("")
    lines.push(phase.summary)
    lines.push("")
    if (phase.keyDeliverables.length) {
      lines.push("**Key deliverables:**")
      lines.push("")
      for (const d of phase.keyDeliverables) lines.push(`- ${d}`)
      lines.push("")
    }
    if (phase.evidence.length) {
      lines.push("**Evidence (repository paths):**")
      lines.push("")
      for (const e of phase.evidence) lines.push(`- \`${e}\``)
      lines.push("")
    }
    if (phase.gaps.length) {
      lines.push("**Remaining gaps:**")
      lines.push("")
      for (const g of phase.gaps) lines.push(`- ${g}`)
      lines.push("")
    }
  }
  lines.push("---")
  lines.push("")
  lines.push(`_Generated by \`scripts/verify-completion-matrix.mjs\` from \`completion-matrix.json\` (schema ${matrix.schemaVersion})._`)
  lines.push("")
  return lines.join("\n")
}

function validate(matrix, matrixPath) {
  let ok = true
  const problems = []

  const report = (cond, message) => {
    if (!cond) {
      ok = false
      problems.push(message)
    }
  }

  report(typeof matrix.schemaVersion === "string" && matrix.schemaVersion.length > 0, "schemaVersion must be a non-empty string")
  report(matrix.metadata && typeof matrix.metadata === "object", "metadata object is required")
  report(matrix.overall && typeof matrix.overall === "object", "overall object is required")
  report(Array.isArray(matrix.phases) && matrix.phases.length > 0, "phases must be a non-empty array")

  if (!matrix.phases) return { ok, problems }

  const ids = new Set()
  for (const phase of matrix.phases) {
    report(phase.id != null && !ids.has(String(phase.id)), `duplicate or missing phase id: ${phase.id}`)
    ids.add(String(phase.id))
    report(typeof phase.name === "string" && phase.name.length > 0, `phase ${phase.id}: name is required`)
    report(VALID_STATUSES.has(phase.status), `phase ${phase.id}: invalid status "${phase.status}"`)
    report(
      typeof phase.percent === "number" && phase.percent >= 0 && phase.percent <= 100,
      `phase ${phase.id}: percent must be a number in [0, 100]`,
    )
    report(Array.isArray(phase.evidence), `phase ${phase.id}: evidence must be an array`)
    for (const ev of phase.evidence || []) {
      // The generated markdown report is produced by this tool itself; its
      // existence is checked by the in-sync comparison instead.
      if (resolve(join(ROOT, ev)) === resolve(DEFAULT_REPORT)) continue
      const full = join(ROOT, ev)
      report(existsSync(full), `phase ${phase.id}: evidence path does not exist: ${ev}`)
    }
    report(Array.isArray(phase.gaps), `phase ${phase.id}: gaps must be an array`)
    report(Array.isArray(phase.keyDeliverables), `phase ${phase.id}: keyDeliverables must be an array`)
  }

  if (matrix.overall) {
    const included = (matrix.overall.includedPhases || []).map((id) => String(id))
    for (const id of included) report(ids.has(id), `overall.includedPhases references unknown phase: ${id}`)
    const excluded = (matrix.overall.excludedPhases || []).map((id) => String(id))
    for (const id of excluded) report(ids.has(id), `overall.excludedPhases references unknown phase: ${id}`)
    report(
      typeof matrix.overall.completionPercent === "number" && matrix.overall.completionPercent >= 0 && matrix.overall.completionPercent <= 100,
      "overall.completionPercent must be a number in [0, 100]",
    )
  }

  return { ok, problems }
}

function main() {
  const args = process.argv.slice(2)
  const write = args.includes("--write")
  const matrixPath = args.find((a) => !a.startsWith("--")) || DEFAULT_MATRIX

  let raw
  try {
    raw = readFileSync(matrixPath, "utf8")
  } catch (err) {
    fail(`cannot read matrix at ${matrixPath}: ${err.message}`)
    return
  }

  let matrix
  try {
    matrix = JSON.parse(raw)
  } catch (err) {
    fail(`completion-matrix.json is not valid JSON: ${err.message}`)
    return
  }

  const { ok, problems } = validate(matrix, matrixPath)
  for (const p of problems) console.error(`   • ${p}`)

  if (!ok) {
    console.error("\n✖ completion-matrix validation FAILED")
    process.exitCode = 1
    return
  }

  const byId = new Map(matrix.phases.map((p) => [p.id, p]))
  const included = matrix.overall.includedPhases.map((id) => byId.get(String(id))).filter(Boolean)
  const equalWeight = included.length
    ? included.reduce((sum, p) => sum + p.percent, 0) / included.length
    : 0

  const md = renderMarkdown(matrix)

  if (write) {
    writeFileSync(DEFAULT_REPORT, md, "utf8")
  } else {
    let existing = ""
    try {
      existing = readFileSync(DEFAULT_REPORT, "utf8")
    } catch {
      /* report missing */
    }
    if (existing !== md) {
      console.error(
        `\n✖ docs/master-plan/completion-matrix.md is out of sync with completion-matrix.json.\n   Run: npm run verify:completion-matrix -- --write`,
      )
      process.exitCode = 1
      return
    }
  }

  console.log("\n✔ completion-matrix validation PASSED")
  console.log(`   Matrix        : ${matrixPath}`)
  console.log(`   Phases        : ${matrix.phases.length} (${matrix.phases.filter((p) => p.status === "completed").length} completed, ${matrix.phases.filter((p) => p.status === "partial").length} partial, ${matrix.phases.filter((p) => p.status === "not-started" || p.status === "out-of-scope").length} not-started)`)
  console.log(`   Declared      : ${formatPercent(matrix.overall.completionPercent)}`)
  console.log(`   Equal-weight  : ${formatPercent(equalWeight)} (included: ${included.length} phases)`)
  console.log(`   Report        : ${DEFAULT_REPORT} ${write ? "(written)" : "(in sync)"}`)
}

main()
