#!/usr/bin/env node
// scripts/generate-cjs-wrapper.mjs
//
// Generates dist/index.cjs — a CJS wrapper for the ESM bundle.
// OpenCode v1.18.4 loads plugins via CJS require() and expects the
// module to export { id, server } as the default export.
import { writeFileSync, existsSync, readFileSync } from "node:fs"
import { join, dirname } from "node:path"
import { fileURLToPath } from "node:url"

const __dir = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dir, "..")
const cjsPath = join(ROOT, "dist", "index.cjs")

const pkg = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf-8"))

// Generate CJS wrapper
const content = `// CJS entry point for OpenCode plugin loader.
// Auto-generated by scripts/generate-cjs-wrapper.mjs
// FlowDeck ${pkg.name}@${pkg.version}

"use strict";
const mod = require("./index.js");
const flowDeckPlugin = mod.default || mod;
module.exports = flowDeckPlugin;
module.exports.default = flowDeckPlugin;
// Named exports for Doctor and internal use
if (mod.AGENT_NAMES) module.exports.AGENT_NAMES = mod.AGENT_NAMES;
if (mod.createAgent) module.exports.createAgent = mod.createAgent;
if (mod.validateDelegationDepth) module.exports.validateDelegationDepth = mod.validateDelegationDepth;
if (mod.evaluateGovernanceToolCheck) module.exports.evaluateGovernanceToolCheck = mod.evaluateGovernanceToolCheck;
if (mod.acquireLock) module.exports.acquireLock = mod.acquireLock;
if (mod.releaseLock) module.exports.releaseLock = mod.releaseLock;
if (mod.cleanupSessionState) module.exports.cleanupSessionState = mod.cleanupSessionState;
if (mod.getSessionMetricsDiagnostics) module.exports.getSessionMetricsDiagnostics = mod.getSessionMetricsDiagnostics;
`

writeFileSync(cjsPath, content, "utf-8")
console.log(`Generated: ${cjsPath}`)
